"""Writes src/icons.generated.ts: the Ionicons subset apps can use, as a woff2 data URL and a name -> codepoint map.

    uv run --with fonttools --with brotli python scripts/icons.py

The font and glyph map come from the frontend's @expo/vector-icons, so app
icons look like the host's tiles. Only the -outline variant of each name in
ICONS.txt ships: the filled glyphs would roughly double the runtime's size.
"""

import base64
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

SDK = Path(__file__).resolve().parent.parent
VENDOR = SDK.parent.parent / "services/frontend/node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons"

glyphs = json.loads((VENDOR / "glyphmaps/Ionicons.json").read_text())

bases = (SDK / "scripts/ICONS.txt").read_text().split()
names = sorted(f"{b}-outline" for b in bases)
missing = [n for n in names if n not in glyphs]
if missing:
    raise SystemExit(f"not in Ionicons: {missing}")

font = TTFont(VENDOR / "Fonts/Ionicons.ttf", recalcTimestamp=False)
options = subset.Options()
options.flavor = "woff2"
options.layout_features = []
options.name_IDs = []
options.notdef_outline = True
sub = subset.Subsetter(options)
sub.populate(unicodes=[glyphs[n] for n in names])
sub.subset(font)
out = io.BytesIO()
font.flavor = "woff2"
font.save(out)
data = base64.b64encode(out.getvalue()).decode()

codes = ",".join(f'"{n}":{glyphs[n]}' for n in names)
union = "\n".join(f"  | '{n}'" for n in names)
(SDK / "src/icons.generated.ts").write_text(
    "// Generated by scripts/icons.py; don't edit.\n"
    f"export const ICON_FONT = 'data:font/woff2;base64,{data}';\n"
    f"export const ICON_CODES: Record<string, number> = {{{codes}}};\n"
)
types = SDK / "types/homeai.d.ts"
text = types.read_text()
start, end = "  // icon names: generated by scripts/icons.py\n", "  // end icon names\n"
i, j = text.index(start) + len(start), text.index(end)
types.write_text(text[:i] + f"  export type IconName =\n{union};\n" + text[j:])
print(f"{len(names)} icons, woff2 {len(out.getvalue())} bytes")
