// Generates expo-host/sandboxAssets.generated.ts: the exact sandbox HTML
// (runtime + groceries app), a v2 app bundle for the hot-reload button, and
// the escape-probe script injected on native.
//   node build/gen-expo-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRuntime } from './build-runtime.mjs';
import { compileApp } from './compile-app.mjs';
import { sandboxHtml } from './sandbox-html.mjs';
import { sandboxProbes } from '../tests/probes.mjs';
import { appVariant } from '../tests/lib.mjs';

const spike = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtime = await buildRuntime();
const v1 = await compileApp(path.join(spike, 'apps/groceries'));
const v2 = await compileApp(appVariant('groceries', 'app/item/[id].tsx', 'Toggle done', 'Toggle done (v2)'));
if (!v1.ok || !v2.ok) throw new Error('app compile failed');

const html = sandboxHtml({ runtime: runtime.code, app: v1.code, config: { initialPath: '/', debug: true } });
const probes = `(async function(){var r=await (${sandboxProbes.toString()})('https://example.com');window.ReactNativeWebView.postMessage(JSON.stringify({homeai:1,kind:'evt',event:'probe.result',data:r}));})();true;`;

const out = path.join(spike, 'expo-host/sandboxAssets.generated.ts');
fs.writeFileSync(
  out,
  `// GENERATED by spikes/app_runtime/build/gen-expo-assets.mjs — do not edit.\n` +
    `export const SANDBOX_HTML = ${JSON.stringify(html)};\n` +
    `export const APP_V2 = ${JSON.stringify(v2.code)};\n` +
    `export const PROBES_JS = ${JSON.stringify(probes)};\n`,
);
console.log(JSON.stringify({ out: path.relative(spike, out), htmlBytes: html.length, runtime: runtime.stats.bytes, app: v1.stats.bytes }));
